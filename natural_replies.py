# ─────────────────────────────────────────────
# دریافت پاسخ تصادفی برای یک حالت
# ─────────────────────────────────────────────

def get_reply(situation, tone="friendly", **kwargs):
    options = REPLIES.get(situation, ["بگو چی می‌خوای؟"])
    reply = random.choice(options)
    if kwargs:
        try:
            reply = reply.format(**kwargs)
        except (KeyError, ValueError):
            pass
    if tone == "urgent" and "سریع" not in reply and "زود" not in reply:
        reply = reply.rstrip(".")
        reply += "، زود باش."
    elif tone == "reassuring" and "نگران" not in reply:
        reply += " نگران نباش."
    return reply


# ─────────────────────────────────────────────
# بهینه‌سازی متن برای ElevenLabs TTS فارسی
# ─────────────────────────────────────────────

def voice_optimize(text):
    if not text:
        return text

    # حذف تگ‌های مارک‌داون
    text = re.sub(r'\*+', '', text)
    text = re.sub(r'_+', '', text)
    text = re.sub(r'`+', '', text)

    # حذف ایموجی‌ها (برای TTS)
    emoji_pattern = re.compile(
        "[\U00010000-\U0010ffff"
        "\U0001F600-\U0001F64F"
        "\U0001F300-\U0001F5FF"
        "\U0001F680-\U0001F6FF"
        "\U0001F1E0-\U0001F1FF"
        "☀-⛿✀-➿]+",
        flags=re.UNICODE
    )
    text = emoji_pattern.sub('', text)

    # تبدیل سه‌نقطه به مکث کوتاه
    text = text.replace("...", ".")

    # فاصله بعد از نقطه
    text = re.sub(r'\.(?=[^\s])', '. ', text)

    # حذف فاصله‌های اضافی
    text = re.sub(r'  +', ' ', text).strip()

    # شکستن جملات خیلی طولانی در نقطه ویرگول
    sentences = []
    for chunk in text.split("."):
        chunk = chunk.strip()
        if not chunk:
            continue
        if len(chunk) > 70:
            parts = chunk.split("،")
            if len(parts) > 1:
                mid = len(parts) // 2
                sentences.append("، ".join(parts[:mid]))
                sentences.append("، ".join(parts[mid:]))
            else:
                sentences.append(chunk)
        else:
            sentences.append(chunk)

    return ". ".join(s for s in sentences if s)
